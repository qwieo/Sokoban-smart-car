#ifndef SOKOBAN_SOLVER3_H
#define SOKOBAN_SOLVER3_H

#include "sokoban_types3.h"

#define LEVEL3_PATH_CAPACITY3 500
#define LEVEL3_INTERNAL_PATH_CAPACITY3 500
#define LEVEL3_RECOGNITION_CAPACITY3 (MAX_BOXES3 * 2)

/* The old internal enums are retained because sokoban_solver3.c still uses
 * them internally. The bomb-first test API below does not require them. */
typedef enum {
    LEVEL3_PREPARE_ERROR3 = -1,
    LEVEL3_PREPARE_READY_PUSH3 = 0,
    LEVEL3_PREPARE_RECOGNIZE3 = 1,
    LEVEL3_PREPARE_BOMB3 = 2,
    LEVEL3_PREPARE_WAIT_RECOGNITION3 = 3
} Level3PrepareResult3;

typedef enum {
    LEVEL3_ACTION_ERROR3 = -1,
    LEVEL3_ACTION_DONE3 = 0,
    LEVEL3_ACTION_EXPLORE3 = 1,
    LEVEL3_ACTION_BOMB3 = 2,
    LEVEL3_ACTION_PUSH3 = 3,
    LEVEL3_ACTION_WAIT_RECOGNITION3 = 4
} Level3Action3;

typedef enum {
    LEVEL3_EASY_ERROR3 = -1,
    LEVEL3_EASY_IDLE3 = 0,
    LEVEL3_EASY_RECOGNIZE_PATH3 = 1,
    LEVEL3_EASY_WAIT_VISION3 = 2,
    LEVEL3_EASY_BOMB_PATH3 = 3,
    LEVEL3_EASY_PUSH_PATH3 = 4,
    LEVEL3_EASY_DONE3 = 5
} Level3EasyState3;

/* Unified output buffer. Every planning function overwrites this buffer. */
extern char level3_commands3[LEVEL3_PATH_CAPACITY3];
extern int level3_steps3;

/* Persistent bomb + recognition path.
 * plan_push_phase3() does not overwrite these two variables. */
extern char bomb_explore_commands3[LEVEL3_PATH_CAPACITY3];
extern int bomb_explore_steps3;

/* Phase-specific lengths. The command bytes are still in level3_commands3. */
extern int bomb_steps3;
extern uint8_t level3_bombs_used3;
extern int explore_steps3;
extern int push_steps3;

/* Recognition coordinates generated by plan_explore_phase3(). */
extern Pos3 expected_targets3[LEVEL3_RECOGNITION_CAPACITY3];
extern int expected_cnt3;

/* 1=recognition, 2=bomb, 3=box push, 4=bomb+recognition fusion. */
extern int level3_segment_type3;
extern uint8_t level3_error3;
extern int level3_error_code3;

/* Recognition-order optimization diagnostics for Keil Watch. */
extern volatile uint32_t g_l3_recog_legacy_dfs_calls3;
extern volatile uint32_t g_l3_recog_move_bfs_calls3;
extern volatile uint32_t g_l3_recog_turn_bfs_calls3;
extern volatile uint32_t g_l3_recog_dp_states3;
extern volatile uint32_t g_l3_recog_dp_transitions3;
extern volatile uint32_t g_l3_recog_pose_count3;
extern volatile uint32_t g_l3_recog_compact_state_capacity3;
extern volatile int32_t g_l3_recog_best_cost3;
extern volatile int32_t g_l3_recog_result3;

/* Fixed-route fusion diagnostics. */
extern int bomb_base_steps3;
extern int route_recognition_cnt3;
extern int remaining_recognition_cnt3;
extern uint8_t level3_joint_fallback3;
extern int level3_joint_candidate_count3;
extern int level3_joint_terminal_push_estimate3;
extern int level3_joint_front_cost3;

/* Interleaved final push diagnostics. */
extern uint8_t level3_multi_push_used3;
extern int level3_multi_push_nodes3;
extern int level3_multi_push_best_cost3;
extern int solver_duplicate_element_group_count;

/* Sequential low-memory fusion: plan all bombs first, then plan N-1
 * recognition from the final bomb pose. Equal-length walking choices are
 * automatically selected for minimum bends while respecting current walls,
 * bombs and boxes. The published output is copied to:
 *   level3_commands3[]       (current shared output)
 *   bomb_explore_commands3[] (persistent front-stage output)
 * bomb_steps3 and explore_steps3 remain available separately. */
void plan_bomb_explore_phase3(char map3[12][16]);

/* Legacy interleaved macro-action planner retained for comparison. */
void plan_joint_bomb_explore_phase3(char map3[12][16]);

/* Fixed preliminary order: bomb -> recognize -> push. */
void plan_bomb_phase3(char map3[12][16]);
void plan_explore_phase3(char map3[12][16]);
void plan_push_phase3(char map3[12][16]);

#endif
